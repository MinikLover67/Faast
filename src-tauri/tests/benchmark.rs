// Local benchmark for Faast's segmented HTTP engine.
//
// Spins up a Range-capable HTTP server that generates bytes on the fly, then
// measures the real engine helpers (split_ranges + download_segment) at
// different connection counts. Run with:
//   cargo test --test benchmark -- --nocapture
//
// These are LOOPBACK numbers. They measure the engine's own overhead and
// scaling, not real internet throughput. See docs/BENCHMARKS.md.

use std::io::{Read, Write};
use std::sync::atomic::{AtomicU64, Ordering};
use std::sync::Arc;
use std::time::Instant;

use faast_lib::{download_segment, split_ranges};

/// Byte value at an index in the synthetic payload.
fn byte_at(i: u64) -> u8 {
    (i % 251) as u8
}

/// Minimal blocking HTTP server with Range support, bytes generated on demand.
fn spawn_generator(total: u64) -> String {
    use std::net::TcpListener;

    let listener = TcpListener::bind("127.0.0.1:0").expect("bind benchmark server");
    let addr = listener.local_addr().expect("local addr");

    std::thread::spawn(move || {
        for stream in listener.incoming() {
            let Ok(mut stream) = stream else { continue };
            let total = total;
            std::thread::spawn(move || {
                let mut buf = [0u8; 4096];
                let n = stream.read(&mut buf).unwrap_or(0);
                let req = String::from_utf8_lossy(&buf[..n]).to_ascii_lowercase();

                // Range: bytes=START-END  (END may be absent)
                let range = req.lines().find_map(|l| {
                    l.strip_prefix("range: bytes=").and_then(|v| {
                        let mut parts = v.trim().split('-');
                        let start = parts.next()?.parse::<u64>().ok()?;
                        let end = parts.next().and_then(|s| s.trim().parse::<u64>().ok());
                        Some((start, end))
                    })
                });

                let (start, end, status) = match range {
                    Some((s, e)) if s < total => {
                        let e = e.unwrap_or(total - 1).min(total - 1);
                        (s, e, "206 Partial Content")
                    }
                    Some(_) => (0, 0, "416 Range Not Satisfiable"),
                    None => (0, total - 1, "200 OK"),
                };
                let len = if status.starts_with("416") { 0 } else { end - start + 1 };

                let head = format!(
                    "HTTP/1.1 {}\r\nContent-Length: {}\r\nAccept-Ranges: bytes\r\nConnection: close\r\n\r\n",
                    status, len
                );
                if stream.write_all(head.as_bytes()).is_err() {
                    return;
                }

                // Stream generated bytes in chunks to avoid a huge allocation.
                let mut pos = start;
                let mut chunk = vec![0u8; 64 * 1024];
                while pos <= end {
                    let take = (end - pos + 1).min(chunk.len() as u64) as usize;
                    for (j, b) in chunk.iter_mut().enumerate().take(take) {
                        *b = byte_at(pos + j as u64);
                    }
                    if stream.write_all(&chunk[..take]).is_err() {
                        return;
                    }
                    pos += take as u64;
                }
            });
        }
    });

    format!("http://{}", addr)
}

#[tokio::test(flavor = "multi_thread", worker_threads = 8)]
async fn segmented_engine_scaling() {
    const TOTAL: u64 = 128 * 1024 * 1024; // 128 MiB
    let base = spawn_generator(TOTAL);
    let url = format!("{}/bench.bin", base);

    let client = reqwest::Client::builder()
        .redirect(reqwest::redirect::Policy::limited(10))
        .user_agent("FaastDownloadManager/1.0")
        .build()
        .expect("client");

    let tmp = std::env::temp_dir();
    println!("\nLocal loopback benchmark — {:.0} MiB synthetic payload", TOTAL as f64 / 1024.0 / 1024.0);
    println!("connections |   seconds |   MB/s");
    println!("------------+-----------+--------");

    for count in [1usize, 8, 16, 32] {
        let counter = Arc::new(AtomicU64::new(0));
        let start = Instant::now();

        if count == 1 {
            // Single-stream baseline: same client, no Range splitting.
            let resp = client.get(&url).send().await.expect("single send");
            assert!(resp.status().is_success());
            use futures_util::stream::StreamExt;
            let mut stream = resp.bytes_stream();
            let path = tmp.join(format!("faast_bench_single.bin"));
            let mut file = tokio::fs::File::create(&path).await.expect("create single");
            use tokio::io::AsyncWriteExt;
            while let Some(chunk) = stream.next().await {
                let chunk = chunk.expect("chunk");
                file.write_all(&chunk).await.expect("write");
                counter.fetch_add(chunk.len() as u64, Ordering::Relaxed);
            }
            file.flush().await.expect("flush");
            drop(file);
            let _ = std::fs::remove_file(&path);
        } else {
            let ranges = split_ranges(TOTAL, count);
            let mut tasks = Vec::new();
            for (i, range) in ranges.iter().enumerate() {
                let client = client.clone();
                let url = url.clone();
                let path = tmp.join(format!("faast_bench_part_{}_{}.bin", count, i));
                let _ = std::fs::remove_file(&path);
                let part = path.to_string_lossy().to_string();
                let counter = counter.clone();
                let range = *range;
                tasks.push(tokio::spawn(async move {
                    download_segment(&client, &url, &part, range, 0, &counter).await
                }));
            }
            for task in tasks {
                task.await.expect("join").expect("segment");
            }
            for i in 0..count {
                let _ = std::fs::remove_file(tmp.join(format!("faast_bench_part_{}_{}.bin", count, i)));
            }
        }

        let elapsed = start.elapsed().as_secs_f64();
        let bytes = counter.load(Ordering::Relaxed);
        assert_eq!(bytes, TOTAL, "byte count for {} connections", count);
        let mbps = bytes as f64 / 1024.0 / 1024.0 / elapsed;
        println!("{:>11} | {:>9.3} | {:>7.1}", count, elapsed, mbps);
    }
}
